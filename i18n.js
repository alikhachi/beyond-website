const I18N_ATTR_MAP = {
  // element selector -> { attr: translationKey }
  '#nav-toggle': { 'aria-label': 'nav.toggleLabel' },
  '.whatsapp-fab': { 'aria-label': 'whatsapp.label' },
  '#name': { placeholder: 'form.name.placeholder' },
  '#email': { placeholder: 'form.email.placeholder' },
  '#message': { placeholder: 'form.message.placeholder' },
};

function getLang() {
  return localStorage.getItem('beyond_lang') || 'ar';
}

function applyTranslations(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.ar;

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'en' ? 'ltr' : 'rtl';
  document.body.classList.toggle('lang-en', lang === 'en');

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  Object.entries(I18N_ATTR_MAP).forEach(([selector, attrs]) => {
    document.querySelectorAll(selector).forEach((el) => {
      Object.entries(attrs).forEach(([attr, key]) => {
        if (dict[key] !== undefined) el.setAttribute(attr, dict[key]);
      });
    });
  });

  const titleKey = document.querySelector('title[data-i18n-title]');
  if (titleKey && dict['meta.title']) document.title = dict['meta.title'];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict['meta.desc']) metaDesc.setAttribute('content', dict['meta.desc']);

  document.querySelectorAll('.lang-switch-label').forEach((el) => {
    el.textContent = dict['nav.langSwitch'];
  });
}

function setLanguage(lang) {
  localStorage.setItem('beyond_lang', lang);
  applyTranslations(lang);
  window.dispatchEvent(new CustomEvent('beyondlangchange', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations(getLang());

  document.querySelectorAll('.lang-toggle').forEach((btn) => {
    btn.addEventListener('click', () => {
      setLanguage(getLang() === 'ar' ? 'en' : 'ar');
    });
  });
});
